import { test, expect } from "@playwright/test";

test("новая категория внутри расхода сохраняет ввод, цвет и иконку", async ({ page }, info) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Расход", exact: true }).click();
  await page.getByLabel("Сумма · RUB").fill("125");
  await page.getByLabel("Заметка").fill("Утренний кофе");
  await page.getByRole("button", { name: "Создать категорию", exact: true }).click();
  await page.getByLabel("Название новой категории").fill("Кофейня");
  await page.getByLabel("Поиск иконки").fill("кофе");
  await page.getByRole("button", { name: "Кофе", exact: true }).click();
  await page.getByLabel("Цвет", { exact: true }).fill("#cc8844");
  await expect(page.getByRole("button", { name: "Кофе", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByLabel("Сумма · RUB")).toHaveValue("125");
  await expect(page.getByLabel("Заметка")).toHaveValue("Утренний кофе");
  await page.screenshot({ path: `test-results/category-${info.project.name}.png`, fullPage: true });
  await page.getByRole("button", { name: "Сохранить", exact: true }).click();
  await expect(page.locator("dialog")).toHaveCount(0);
  await expect(page.locator(".entry-name")).toContainText("Кофейня");
  await expect(page.locator(".entry .category-icon")).toHaveCSS("color", "rgb(204, 136, 68)");
  await expect(page.locator(".entry .lucide-coffee")).toHaveCount(1);
  await page.reload();
  await expect(page.locator(".entry .lucide-coffee")).toHaveCount(1);
  await page.getByRole("button", { name: "Расход", exact: true }).click();
  await page.getByLabel("Сумма · RUB").fill("10");
  await page.getByRole("button", { name: "Создать категорию", exact: true }).click();
  await page.getByLabel("Название новой категории").fill("Кофейня");
  await page.getByRole("button", { name: "Сохранить", exact: true }).click();
  await expect(page.locator("dialog [role=alert]")).toContainText("Такая категория уже есть");
  await expect(page.getByLabel("Сумма · RUB")).toHaveValue("10");
  await page.getByRole("button", { name: "Закрыть", exact: true }).click();
  await expect(page.locator(".entry")).toHaveCount(1);
  await page.getByRole("button", { name: "Доход", exact: true }).click();
  await page.getByLabel("Сумма · RUB").fill("500");
  await page.getByRole("button", { name: "Создать категорию", exact: true }).click();
  await page.getByLabel("Название новой категории").fill("Подработка");
  await page.getByRole("button", { name: "Сохранить", exact: true }).click();
  await expect(page.locator(".entry-name").filter({ hasText: "Подработка" })).toHaveCount(1);
  await page.getByRole("button", { name: "Расход", exact: true }).click();
  await expect(page.locator(".category-picker")).not.toContainText("Подработка");
  await page.getByRole("button", { name: "Создать категорию", exact: true }).click();
  await page.getByLabel("Название новой категории").fill("Отменённая");
  await page.getByRole("button", { name: "Закрыть", exact: true }).click();
  await page.getByRole("button", { name: "Настройки", exact: true }).click();
  await expect(page.locator(".category-chips").filter({ hasText: "Отменённая" })).toHaveCount(0);
});
